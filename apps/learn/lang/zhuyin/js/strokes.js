/* 0–100 格座標（y 向下）→ HanziWriter 座標（1024 寬，y 向上，基線 900） */
function _zyToHw(p) { return [Math.round(62 + p[0] * 9), Math.round(838 - p[1] * 9)]; }

/* 中心線每段切細，讓動畫與比對有足夠取樣點 */
function _zyResample(pts, step) {
  var out = [pts[0]];
  for (var i = 1; i < pts.length; i++) {
    var a = pts[i - 1], b = pts[i];
    var n = Math.max(1, Math.ceil(Math.hypot(b[0] - a[0], b[1] - a[1]) / step));
    for (var k = 1; k <= n; k++) out.push([a[0] + (b[0] - a[0]) * k / n, a[1] + (b[1] - a[1]) * k / n]);
  }
  return out;
}

/* 外形 = 每段一個長方形＋每個轉折點一個圓（圓頭圓角），所有子路徑同一方向繞行，
   nonzero 填色規則下自然聯集成一筆完整筆畫，不用處理折角自交 */
function _zyRing(pts) {
  var area = 0;
  for (var i = 0; i < pts.length; i++) {
    var a = pts[i], b = pts[(i + 1) % pts.length];
    area += a[0] * b[1] - b[0] * a[1];
  }
  if (area < 0) pts = pts.slice().reverse();
  return 'M ' + pts.map(function(p) { return p[0].toFixed(1) + ' ' + p[1].toFixed(1); }).join(' L ') + ' Z';
}

function _zyOutline(pts, hw) {
  var parts = [];
  for (var i = 1; i < pts.length; i++) {
    var a = pts[i - 1], b = pts[i];
    var len = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1;
    var nx = -(b[1] - a[1]) / len * hw, ny = (b[0] - a[0]) / len * hw;
    parts.push(_zyRing([[a[0] + nx, a[1] + ny], [b[0] + nx, b[1] + ny], [b[0] - nx, b[1] - ny], [a[0] - nx, a[1] - ny]]));
  }
  pts.forEach(function(p) {
    var c = [];
    for (var k = 0; k < 20; k++) {
      var t = k / 20 * Math.PI * 2;
      c.push([p[0] + Math.cos(t) * hw, p[1] + Math.sin(t) * hw]);
    }
    parts.push(_zyRing(c));
  });
  return parts.join(' ');
}

var _zyHwCache = {};
function zyStrokeData(symbol) {
  if (_zyHwCache[symbol]) return _zyHwCache[symbol];
  var src = ZY_STROKE_MEDIANS[symbol];
  if (!src) return null;
  var data = { strokes: [], medians: [] };
  src.forEach(function(stroke) {
    var pts = stroke.map(_zyToHw);
    data.strokes.push(_zyOutline(pts, 34));
    data.medians.push(_zyResample(pts, 60).map(function(p) { return [Math.round(p[0]), Math.round(p[1])]; }));
  });
  _zyHwCache[symbol] = data;
  return data;
}

/* HanziWriter charDataLoader：只吃本檔資料，不去 CDN 抓 */
function zyCharDataLoader(symbol, onComplete, onError) {
  var d = zyStrokeData(symbol);
  if (d) onComplete(d); else if (onError) onError(new Error('no zhuyin stroke data: ' + symbol));
}
